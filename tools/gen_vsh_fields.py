#!/usr/bin/env python3
"""Regenerates crates/ferrox-nv2a/src/vsh_fields.rs from xemu's field table.

usage: gen_vsh_fields.py path/to/xemu/hw/xbox/nv2a/pgraph/glsl/vsh-prog.c > crates/ferrox-nv2a/src/vsh_fields.rs
"""
import re, sys

src = open(sys.argv[1]).read()
table = re.search(r"field_mapping\[\] = \{(.*?)\n\};", src, re.S).group(1)
rows = re.findall(r"\{\s*FLD_(\w+),\s*(\d+),\s*(\d+),\s*(\d+)\s*\}", table)
print("// Generated by tools/gen_vsh_fields.py from xemu (hw/xbox/nv2a/pgraph/glsl/vsh-prog.c, field_mapping). Do not edit.")
print("//! Where each field of a vertex-program instruction sits: (word, first bit, bit count).")
print()
for name, word, start, length in rows:
    print(f"pub const {name}: (usize, u32, u32) = ({word}, {start}, {length});")
